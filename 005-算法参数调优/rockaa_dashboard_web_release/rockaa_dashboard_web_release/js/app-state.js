  if (typeof refreshEffectTuningLanguage === 'function') refreshEffectTuningLanguage();
  if (typeof renderMigrationMatrix === 'function') renderMigrationMatrix();
  if (typeof refreshConfigHistory === 'function') refreshConfigHistory();
